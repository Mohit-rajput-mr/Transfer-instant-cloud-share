# Voiceover with feeling (emotion 0.75-1.2 per line: higher = livelier; above ~1.4 the voice strains): Chatterbox (open model, run locally, CPU) cloned from the house voice (Kokoro bm_george,
# ref_george.wav), with an emotion level per line. Every take is checked by a speech recogniser (faster-whisper):
# the best-matching of up to 3 takes is kept, so no garbled line gets through.
#   python vo.py            (needs: pip install chatterbox-tts faster-whisper jiwer soundfile "setuptools<81")
import json, re, sys
import numpy as np, soundfile as sf, librosa, torch, jiwer
from chatterbox.tts import ChatterboxTTS
from faster_whisper import WhisperModel

# (key, subtitle text, emotion 0..1, pause after in s). "Orbi" is spoken "Orbee".
LINES = [
    ("hook",    "Do you know how the codes in Google Authenticator work, even with no signal?",                              1.05, 0.45),
    ("scene",   "Google Authenticator, Microsoft Authenticator, they all make a new code every thirty seconds. The website somehow knows it too. And they never talk!", 1.05, 0.30),
    ("secret",  "When you scanned that QR code, your phone and the website got the same secret key. Just once.",     0.95, 0.30),
    ("clock",   "Now both sides take that secret, plus the time, rounded to thirty seconds.",                         0.95, 0.30),
    ("blend",   "They drop both into the same mathematical blender, and keep six digits of what comes out.",         1.05, 0.30),
    ("match",   "Same secret, same time, same blender. Same six digits! Nothing had to be sent.",                     1.10, 0.35),
    ("steal",   "And if someone peeks at your code? Thirty seconds later, it's useless.",                              1.00, 0.40),
    ("orbi",    "Orbi Transfer keeps a secret the same way. Your passcode never leaves your phone. Only locked pieces travel.", 1.05, 0.40),
    ("end",     "Orbi Transfer dot com. Now you know!",                                                               1.05, 0.00),
]

torch.set_num_threads(4)
tts = ChatterboxTTS.from_pretrained(device="cpu")
asr = WhisperModel("small.en", device="cpu", compute_type="int8")
norm = lambda s: re.sub(r"[^a-z0-9 ]", "", s.lower().replace("orbee", "orbi").replace("orby", "orbi").replace("thirty", "30").replace("forty", "40").replace("café", "cafe").replace("48000", "40 eight thousand").replace("48,000", "40 eight thousand").replace("six-digit", "six digit").replace("6-digit", "six digit").replace("wi-fi", "wifi").replace("wi fi", "wifi").replace("e-sim", "esim").replace("e sim", "esim").replace("cue are", "qr").replace("q r", "qr").replace("twenty", "20").replace("kilometers", "kilometres").replace("seconds", "seconds")).split()


def trim(y, sr):
    yt, idx = librosa.effects.trim(y, top_db=38)
    pad = int(0.06 * sr)
    return y[max(0, idx[0] - pad): idx[1] + pad]


def wer(ref, y, sr):
    segs, _ = asr.transcribe(librosa.resample(y, orig_sr=sr, target_sr=16000), language="en")
    hyp = " ".join(s.text for s in segs)
    return jiwer.wer(" ".join(norm(ref)), " ".join(norm(hyp)) or "x"), hyp


only = set(sys.argv[1:])
out, at = [], 0.35
prev = json.load(open("vo/lines.json")) if only else None
for key, text, ex, gap in LINES:
    if only and key not in only:
        ln = next(l for l in prev["lines"] if l["key"] == key)
        d = ln["dur"]
    else:
        spoken = text.replace("Orbi", "Orbee")
        best = None
        for take in range(3):
            torch.manual_seed(take * 7 + len(key))
            w = tts.generate(spoken, audio_prompt_path="ref_george.wav", exaggeration=ex, cfg_weight=max(0.25, 0.5 - 0.2 * ex), temperature=0.8)
            y = trim(w.squeeze(0).numpy(), tts.sr)
            e, hyp = wer(text, y, tts.sr)
            print(f"{key} take {take}: wer {e:.2f} · {hyp.strip()}", flush=True)
            if best is None or e < best[0]:
                best = (e, y)
            if e <= 0.05:
                break
        y = best[1] / max(1e-6, np.abs(best[1]).max()) * 0.92
        sf.write(f"vo/{key}.wav", y, tts.sr, subtype="PCM_16")
        d = len(y) / tts.sr
    out.append({"key": key, "text": text, "dur": round(d, 3), "at": round(at, 2)})
    at += d + gap
    print(key, round(d, 2), flush=True)
json.dump({"sr": tts.sr, "lines": out, "duration": round(at + 1.8, 2)}, open("vo/lines.json", "w"), indent=1)
print("duration", round(at + 1.8, 1))
